/**
 * Enriches the local film catalog with TMDB poster paths without rewriting the
 * generated film dataset. It is resumable: every processed IMDb ID is kept in
 * src/data/poster-catalog.js, including misses as null.
 *
 * Usage (PowerShell):
 *   $env:TMDB_READ_ACCESS_TOKEN="..."; node tools/catalog/enrich-posters-tmdb.js
 * Optional: $env:POSTER_BATCH_LIMIT=100
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCatalog } from '../../src/infrastructure/catalog.ts';

const dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(dirname, '..', '..');
const outputPath = path.join(root, 'src', 'data', 'poster-catalog.js');
const token = process.env.TMDB_READ_ACCESS_TOKEN || '';
const delayMs = 110;
const batchLimit = Number.parseInt(process.env.POSTER_BATCH_LIMIT || '', 10) || Infinity;
const batchSize = 50;

const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));

function readPosterMap() {
  if (!fs.existsSync(outputPath)) return {};
  const source = fs.readFileSync(outputPath, 'utf8');
  const start = source.indexOf('{');
  const end = source.lastIndexOf('}');
  if (start < 0 || end < start) throw new Error('poster_catalog.js inválido.');
  return JSON.parse(source.slice(start, end + 1));
}

function savePosterMap(map) {
  const ordered = Object.fromEntries(Object.entries(map).sort(([a], [b]) => a.localeCompare(b)));
  const content = [
    '// Generated by tools/catalog/enrich-posters-tmdb.js. Do not add credentials here.',
    'export const POSTER_PATHS_BY_IMDB_ID = Object.freeze(',
    `${JSON.stringify(ordered, null, 2)}`,
    ');',
    ''
  ].join('\n');
  fs.writeFileSync(outputPath, content, 'utf8');
}

async function getPosterPath(imdbId) {
  const url = new URL(`https://api.themoviedb.org/3/find/${encodeURIComponent(imdbId)}`);
  url.searchParams.set('external_source', 'imdb_id');
  const response = await fetch(url, {
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: 'application/json'
    },
    signal: AbortSignal.timeout(10000)
  });
  if (!response.ok) throw new Error(`TMDB respondeu HTTP ${response.status}`);
  const data = await response.json();
  return data.movie_results?.[0]?.poster_path || null;
}

async function main() {
  if (!token) throw new Error('TMDB_READ_ACCESS_TOKEN não configurado.');

  const posterMap = readPosterMap();
  const uniqueIds = [...new Set(loadCatalog().films.map(film => film.imdbId).filter(Boolean))];
  const pending = uniqueIds.filter(imdbId => !Object.hasOwn(posterMap, imdbId)).slice(0, batchLimit);
  console.log(`Pôsteres conhecidos: ${Object.keys(posterMap).length}/${uniqueIds.length}. Processando ${pending.length}.`);

  let found = 0;
  let missing = 0;
  for (let index = 0; index < pending.length; index++) {
    const imdbId = pending[index];
    try {
      const posterPath = await getPosterPath(imdbId);
      posterMap[imdbId] = posterPath;
      if (posterPath) found++;
      else missing++;
    } catch (error) {
      console.error(`\n${imdbId}: ${error.message}`);
      savePosterMap(posterMap);
      throw error;
    }

    if ((index + 1) % batchSize === 0) savePosterMap(posterMap);
    if ((index + 1) % 25 === 0 || index + 1 === pending.length) {
      process.stdout.write(`\r${index + 1}/${pending.length} · ${found} encontrados · ${missing} sem pôster`);
    }
    await sleep(delayMs);
  }
  savePosterMap(posterMap);
  console.log('\nConcluído. Execute novamente para continuar, se necessário.');
}

main().catch(error => {
  console.error(`\nErro: ${error.message}`);
  process.exitCode = 1;
});
